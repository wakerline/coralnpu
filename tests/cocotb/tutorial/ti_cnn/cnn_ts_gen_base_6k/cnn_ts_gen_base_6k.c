static inline __attribute__((always_inline)) void conv1d_relu_f32(float *out, const float *in, uint64_t in_ch,
                            uint64_t in_len, uint64_t out_ch, uint64_t k_len,
                            uint64_t stride, uint64_t pad, uint64_t group,
                            const float *weight, const float *bias) {
  const uint64_t icpg = in_ch / group;
  const uint64_t ocpg = out_ch / group;
  const uint64_t out_len = (in_len + 2 * pad - k_len) / stride + 1;
  uint64_t first_valid = (pad + stride - 1) / stride;
  uint64_t last_valid = 0;
  if (in_len + pad >= k_len)
    last_valid = (in_len + pad - k_len) / stride;
  if (first_valid > out_len)
    first_valid = out_len;
  if (last_valid >= out_len)
    last_valid = out_len - 1;
  if (last_valid + 1 < first_valid)
    first_valid = out_len;

  for (uint64_t oc = 0; oc < out_ch; ++oc) {
    const uint64_t g = oc / ocpg;
    const uint64_t in_base_ch = g * icpg;

    for (uint64_t t = 0; t < first_valid; ++t) {
      float acc = bias[oc];
      for (uint64_t icg = 0; icg < icpg; ++icg) {
        for (uint64_t k = 0; k < k_len; ++k) {
          int64_t it = (int64_t)(t * stride + k) - (int64_t)pad;
          if (it >= 0 && it < (int64_t)in_len) {
            uint64_t widx = (oc * icpg + icg) * k_len + k;
            acc += in[(in_base_ch + icg) * in_len + (uint64_t)it] * weight[widx];
          }
        }
      }
      out[oc * out_len + t] = acc < 0.0f ? 0.0f : acc;
    }

    if (first_valid < out_len) {
      for (uint64_t t = first_valid; t <= last_valid; ++t) {
        float acc = bias[oc];
        const uint64_t base = t * stride - pad;
        for (uint64_t icg = 0; icg < icpg; ++icg) {
          const float *in_ch_ptr = in + (in_base_ch + icg) * in_len + base;
          for (uint64_t k = 0; k < k_len; ++k) {
            uint64_t widx = (oc * icpg + icg) * k_len + k;
            acc += in_ch_ptr[k] * weight[widx];
          }
        }
        out[oc * out_len + t] = acc < 0.0f ? 0.0f : acc;
      }
    }

    const uint64_t tail_start = first_valid < out_len ? last_valid + 1 : out_len;
    for (uint64_t t = tail_start; t < out_len; ++t) {
      float acc = bias[oc];
      for (uint64_t icg = 0; icg < icpg; ++icg) {
        for (uint64_t k = 0; k < k_len; ++k) {
          int64_t it = (int64_t)(t * stride + k) - (int64_t)pad;
          if (it >= 0 && it < (int64_t)in_len) {
            uint64_t widx = (oc * icpg + icg) * k_len + k;
            acc += in[(in_base_ch + icg) * in_len + (uint64_t)it] * weight[widx];
          }
        }
      }
      out[oc * out_len + t] = acc < 0.0f ? 0.0f : acc;
    }
  }
}

static inline __attribute__((always_inline)) void maxpool1d_f32(float *out, const float *in, uint64_t channels,
                          uint64_t in_len, uint64_t k_len, uint64_t stride,
                          uint64_t pad) {
  const uint64_t out_len = (in_len + 2 * pad - k_len) / stride + 1;
  if (pad == 1 && k_len == 3 && stride == 2) {
    for (uint64_t c = 0; c < channels; ++c) {
      const float *in_c = in + c * in_len;
      float *out_c = out + c * out_len;
      float m0 = in_c[0];
      if (in_c[1] > m0)
        m0 = in_c[1];
      out_c[0] = m0;
      for (uint64_t t = 1; t < out_len; ++t) {
        const float *p = in_c + 2 * t - 1;
        float maxv = p[0];
        if (p[1] > maxv)
          maxv = p[1];
        if (p[2] > maxv)
          maxv = p[2];
        out_c[t] = maxv;
      }
    }
    return;
  }
  if (pad == 0) {
    for (uint64_t c = 0; c < channels; ++c) {
      const float *in_c = in + c * in_len;
      float *out_c = out + c * out_len;
      for (uint64_t t = 0; t < out_len; ++t) {
        const float *p = in_c + t * stride;
        float maxv = p[0];
        for (uint64_t k = 1; k < k_len; ++k) {
          float v = p[k];
          if (v > maxv)
            maxv = v;
        }
        out_c[t] = maxv;
      }
    }
    return;
  }
  for (uint64_t c = 0; c < channels; ++c) {
    for (uint64_t t = 0; t < out_len; ++t) {
      float maxv = -3.402823466e+38f;
      for (uint64_t k = 0; k < k_len; ++k) {
        int64_t it = (int64_t)(t * stride + k) - (int64_t)pad;
        if (it >= 0 && it < (int64_t)in_len) {
          float v = in[c * in_len + (uint64_t)it];
          if (v > maxv)
            maxv = v;
        }
      }
      out[c * out_len + t] = maxv;
    }
  }
}

static inline __attribute__((always_inline, unused)) void avgpool1d_f32(float *out, const float *in, uint64_t channels,
                          uint64_t in_len, uint64_t k_len, uint64_t stride,
                          uint64_t pad) {
  const uint64_t out_len = (in_len + 2 * pad - k_len) / stride + 1;
  if (pad == 0) {
    const float inv_count = 1.0f / (float)k_len;
    for (uint64_t c = 0; c < channels; ++c) {
      const float *in_c = in + c * in_len;
      float *out_c = out + c * out_len;
      for (uint64_t t = 0; t < out_len; ++t) {
        const float *p = in_c + t * stride;
        float sum = 0.0f;
        for (uint64_t k = 0; k < k_len; ++k)
          sum += p[k];
        out_c[t] = sum * inv_count;
      }
    }
    return;
  }
  for (uint64_t c = 0; c < channels; ++c) {
    for (uint64_t t = 0; t < out_len; ++t) {
      float sum = 0.0f;
      uint64_t count = 0;
      for (uint64_t k = 0; k < k_len; ++k) {
        int64_t it = (int64_t)(t * stride + k) - (int64_t)pad;
        if (it >= 0 && it < (int64_t)in_len) {
          sum += in[c * in_len + (uint64_t)it];
          ++count;
        }
      }
      out[c * out_len + t] = sum / (float)count;
    }
  }
}

static inline __attribute__((always_inline)) void avgpool_linear_f32(float *out, const float *in,
                                uint64_t channels, uint64_t in_len,
                                uint64_t k_len, uint64_t stride) {
  const uint64_t out_len = (in_len - k_len) / stride + 1;
  float acc0 = fc_bias[0];
  float acc1 = fc_bias[1];
  const float inv_count = 1.0f / (float)k_len;
  uint64_t idx = 0;
  for (uint64_t c = 0; c < channels; ++c) {
    const float *in_c = in + c * in_len;
    for (uint64_t t = 0; t < out_len; ++t, ++idx) {
      const float *p = in_c + t * stride;
      float sum = 0.0f;
      for (uint64_t k = 0; k < k_len; ++k)
        sum += p[k];
      const float feature = sum * inv_count;
      acc0 += feature * fc_weight[idx];
      acc1 += feature * fc_weight[CNN_TS_GEN_BASE_6K_FC_IN + idx];
    }
  }
  out[0] = acc0;
  out[1] = acc1;
}

static inline __attribute__((always_inline)) void batch_norm(float *out, const float *in) {
  for (uint64_t i = 0; i < 256; ++i)
    out[i] = in[i] * bn_scale[0] + bn_bias[0];
}

static inline __attribute__((always_inline, unused)) void linear(float *out, const float *in) {
  for (uint64_t o = 0; o < 2; ++o) {
    float acc = fc_bias[o];
    for (uint64_t i = 0; i < CNN_TS_GEN_BASE_6K_FC_IN; ++i)
      acc += in[i] * fc_weight[o * CNN_TS_GEN_BASE_6K_FC_IN + i];
    out[o] = acc;
  }
}

